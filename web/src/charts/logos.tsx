/** A lab's mark, `size` px square, centred on (x, y). */
export function LabLogo({ lab, x, y, size = 18 }: { lab: LabId; x: number; y: number; size?: number }) {
  const m = MARKS[lab];
  // A mark on a tile is drawn smaller inside it.
  const inner = m.tile ? 0.66 : 1;
  const k = (size * inner) / 24;
  const off = (size - size * inner) / 2;
  return (
    <g transform={`translate(${x - size / 2} ${y - size / 2})`} aria-hidden>
      {m.tile && <rect width={size} height={size} rx={size * 0.18} fill={m.tile} />}
      <g transform={`translate(${off} ${off}) scale(${k})`} fillRule="evenodd">
        {m.paths.map((p) => (
          <path key={p.d.slice(0, 24)} d={p.d} fill={p.fill} />
        ))}
      </g>
    </g>
  );
}
